def launchd_available() -> bool:
    return sys.platform == "darwin" and os.path.exists(LAUNCHCTL)


def _launchctl(args: List[str]) -> Tuple[int, str]:
    proc = subprocess.run([LAUNCHCTL, *args], capture_output=True, text=True)
    return proc.returncode, (proc.stdout if proc.returncode == 0 else proc.stderr).strip()


def _getenv(name: str, run: Callable) -> str:
    rc, out = run(["getenv", name])
    return out if rc == 0 else ""


# --------------------------------------------------------------------------
# Plan: shared by deploy and diff
# --------------------------------------------------------------------------


@dataclass
class Plan:
    errors: List[str] = field(default_factory=list)
    spec: Optional[Spec] = None
    var_rows: List[str] = field(default_factory=list)
    # (path, data, action, why the existing file is moved aside first or None)
    write: List[Tuple[str, bytes, str, Optional[str]]] = field(default_factory=list)
    adopt: List[Tuple[str, str]] = field(default_factory=list)  # (path, hash)
    blocked: List[Tuple[str, str]] = field(default_factory=list)
    remove: List[str] = field(default_factory=list)
    forget: List[Tuple[str, str]] = field(default_factory=list)
    setenv: List[Tuple[str, str]] = field(default_factory=list)
    unsetenv: List[str] = field(default_factory=list)
    launchd_forget: List[Tuple[str, str]] = field(default_factory=list)
    warnings: List[str] = field(default_factory=list)


def _hash(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _file_hash(path: str) -> Optional[str]:
    try:
        with open(path, "rb") as f:
            return _hash(f.read())
    except OSError:
        return None


def _var_rows(spec: Optional[Spec], section: Dict) -> List[str]:
    old_vars = section.get("vars") or {}
    new_vars = spec.vars if spec else {}
    rows = []
    for name, value in new_vars.items():
        if name not in old_vars:
            rows.append(f"  + {name}={value}")
        elif old_vars[name] != value:
            rows.append(f"  ~ {name}={value} (was {old_vars[name]})")
    rows += [f"  - {name}" for name in old_vars if name not in new_vars]
    old_path = section.get("path") or []
    new_path = spec.path if spec else []
    if old_path != new_path:
        rows.append(f"  ~ path: {os.pathsep.join(new_path)}" if new_path else "  - path")
    return rows


def plan(raw, state: Dict, conflicts=None, run: Optional[Callable] = None) -> Plan:
    section = state.get("env", {}) or {}
    installed: Dict[str, Dict] = section.get("files", {}) or {}
    p = Plan()
    if raw is None:
        spec, p.errors = None, []
    else:
        spec, p.errors = parse(raw)
    if p.errors:
        return p
    p.spec = spec
    p.var_rows = _var_rows(spec, section)

    desired = spec.files() if spec else {}
    for target, shell in desired.items():
        reason = conflicts.get(target) if conflicts else None
        if reason:
            p.blocked.append((target, reason))
            continue
        data = render(spec, shell)
        if os.path.islink(target):
            p.write.append((target, data, "replace", "a symlink"))
            continue
        if os.path.lexists(target) and not os.path.isfile(target):
            p.blocked.append((target, "exists and is not a regular file"))
            continue
        current = _file_hash(target) if os.path.lexists(target) else None
        recorded = (installed.get(target) or {}).get("hash")
        if current is None and not os.path.lexists(target):
            p.write.append((target, data, "create", None))
        elif current != _hash(data):
            if target not in installed:
                p.write.append((target, data, "replace", "not tracked by tools"))
            elif current != recorded:
                p.write.append((target, data, "replace", "changed since tools wrote it"))
            else:
                p.write.append((target, data, "update", None))
        elif (installed.get(target) or {}).get("hash") != current:
            p.adopt.append((target, current))

    for item in list(p.write):
        refused = item[3] and fsutil.aside_refused(item[0])
        if refused:
            p.write.remove(item)
            p.blocked.append((item[0], refused))
    for target in sorted(set(installed) - set(desired)):
        record = installed.get(target) or {}
        if not os.path.lexists(target):
            p.forget.append((target, "already gone"))
        elif record.get("hash") and _file_hash(target) == record["hash"]:
            p.remove.append(target)
        else:
            p.forget.append((target, "changed since tools wrote it; left in place"))

    tracked_env: Dict[str, str] = section.get("launchd", {}) or {}
    want_env = spec.vars if spec and spec.launchd else {}
    if (want_env or tracked_env) and not launchd_available():
        if spec and spec.launchd:
            p.warnings.append("launchd: launchctl is not available here; skipped")
        return p
    run = run or _launchctl
    for name, value in want_env.items():
        if _getenv(name, run) != value:
            p.setenv.append((name, value))
    for name in sorted(set(tracked_env) - set(want_env)):
        current = _getenv(name, run)
        if current == tracked_env[name]:
            p.unsetenv.append(name)
        elif current:
            p.launchd_forget.append((name, "changed since tools set it; left in place"))
        else:
            p.launchd_forget.append((name, "already unset"))
    return p


