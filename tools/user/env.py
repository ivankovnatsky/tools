def prepend_path(current: str, dirs: List[str]) -> str:
    """Same result as sourcing the snippet: ``dirs`` first, no duplicates."""
    rest = [p for p in current.split(os.pathsep) if p and p not in dirs] if current else []
    return os.pathsep.join([*dirs, *rest])


# What the last export set, so a long-running `tools watch` drops removed vars.
_exported: Dict[str, str] = {}


def export_process(raw, environ=None, exported: Optional[Dict[str, str]] = None) -> bool:
    """Export the section into ``environ`` (os.environ). False if invalid or absent.

    A var an earlier call exported and the config no longer declares is
    removed again, unless something else has changed it since.
    """
    environ = os.environ if environ is None else environ
    exported = _exported if exported is None else exported
    spec, errors = parse(raw) if raw else (None, [])
    if errors:
        return False
    want = spec.vars if spec else {}
    for name, value in list(exported.items()):
        if name not in want and environ.get(name) == value:
            environ.pop(name, None)
        exported.pop(name)
    if not spec:
        return False
    environ.update(want)
    exported.update(want)
    if spec.path:
        environ["PATH"] = prepend_path(environ.get("PATH", ""), spec.path)
    return True


