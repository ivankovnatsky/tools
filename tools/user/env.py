"""Session environment: variables and PATH entries for every shell.

Config shape::

    env:
      vars:
        EDITOR: nvim
        HF_HOME: ${externalStoragePath}/.cache/huggingface
      path:                    # prepended to PATH, first entry first
        - ~/.local/bin
      shells: [sh, fish, nu]   # default: all three
      dir: ~/.local/state/tools/env
      launchd: false           # darwin: also `launchctl setenv` each var

Deploy renders ``env.sh`` (bash, zsh, dash), ``env.fish`` and ``env.nu``
into ``dir`` for rc files to source, and exports the same values into
this process so every later section (uv, npm, ...) sees them, whatever
``--scope`` says.

Values are written literally: no shell expansion in any of the three
shells, so ``$HOME`` stays ``$HOME``. A leading ``~`` is expanded at
deploy time; use ``${env:NAME}`` or ``vars`` for anything else. Secrets
are refused: values land in world-readable files and in every process.

Sourcing is idempotent: re-sourcing moves each ``path`` entry to the
front instead of adding it again.
"""

import hashlib
import os
import re
import subprocess
import sys
from dataclasses import dataclass, field
from typing import Callable, Dict, List, Mapping, Optional, Tuple

from tools import fsutil
from tools.log import Color, debug, log
from tools.util import looks_like_secret

DEFAULT_DIR = "~/.local/state/tools/env"
SHELLS = ("sh", "fish", "nu")
LAUNCHCTL = "/bin/launchctl"
FILE_MODE = 0o644

_KEYS = {"vars", "path", "shells", "dir", "launchd"}
_NAME = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
_CONTROL = re.compile(r"[\x00-\x1f\x7f]")
_RESERVED = {"PATH": "set PATH through env.path"}
_HEADER = "Generated by tools (env section). Do not edit; changes are overwritten."


@dataclass
class Spec:
    vars: Dict[str, str]
    path: List[str]
    shells: List[str]
    dir: str
    launchd: bool

    def files(self) -> Dict[str, str]:
        """{target path: shell}."""
        return {os.path.join(self.dir, f"env.{shell}"): shell for shell in self.shells}


def _expand_home(value: str) -> str:
    if value == "~" or value.startswith("~/"):
        return os.path.expanduser(value)
    return value


def parse(raw) -> Tuple[Optional[Spec], List[str]]:
    """Validate config into a Spec. Any error rejects the whole section."""
    if raw is None:
        raw = {}
    if not isinstance(raw, Mapping):
        return None, [f"env must be a mapping, got {type(raw).__name__}"]
    errors: List[str] = []
    unknown = set(raw) - _KEYS
    if unknown:
        errors.append(f"unknown keys {sorted(unknown)}")

    vars_raw = raw.get("vars") or {}
    env_vars: Dict[str, str] = {}
    if not isinstance(vars_raw, Mapping):
        errors.append(f"env.vars must be a mapping, got {type(vars_raw).__name__}")
        vars_raw = {}
    for name, value in vars_raw.items():
        where = f"env.vars.{name}"
        if not isinstance(name, str) or not _NAME.fullmatch(name):
            errors.append(f"{where}: invalid name (use [A-Za-z_][A-Za-z0-9_]*)")
            continue
        if name in _RESERVED:
            errors.append(f"{where}: {_RESERVED[name]}")
            continue
        if isinstance(value, bool) or not isinstance(value, (str, int, float)):
            errors.append(
                f"{where}: value must be a string or number, got {type(value).__name__}"
                + (" (quote it)" if isinstance(value, bool) else "")
            )
            continue
        text = _expand_home(str(value))
        if _CONTROL.search(text):
            errors.append(f"{where}: control characters are not allowed")
            continue
        if looks_like_secret(text.encode()):
            errors.append(
                f"{where}: looks like a secret; env values are plaintext in every process "
                "(point at a file with ${sopsPath:NAME} instead)"
            )
            continue
        env_vars[name] = text

    path_raw = raw.get("path") or []
    path: List[str] = []
    if not isinstance(path_raw, list):
        errors.append(f"env.path must be a list, got {type(path_raw).__name__}")
        path_raw = []
    for i, entry in enumerate(path_raw):
        where = f"env.path[{i}]"
        if not isinstance(entry, str) or not entry:
            errors.append(f"{where}: must be a non-empty string")
            continue
        expanded = os.path.normpath(_expand_home(entry))
        if not os.path.isabs(expanded):
            errors.append(f"{where}: {entry!r} must be absolute (or start with ~)")
        elif ":" in expanded or _CONTROL.search(expanded):
            errors.append(f"{where}: {entry!r} contains ':' or a control character")
        elif expanded not in path:
            path.append(expanded)

    shells_raw = raw.get("shells", list(SHELLS))
    shells: List[str] = []
    if not isinstance(shells_raw, list) or not all(isinstance(s, str) for s in shells_raw):
        errors.append(f"env.shells must be a list of {', '.join(SHELLS)}")
    else:
        bad = [s for s in shells_raw if s not in SHELLS]
        if bad:
            errors.append(f"env.shells: unknown {bad} (use {', '.join(SHELLS)})")
        shells = [s for s in SHELLS if s in shells_raw]

    dir_raw = raw.get("dir") or DEFAULT_DIR
    out_dir = ""
    if not isinstance(dir_raw, str):
        errors.append("env.dir must be a path string")
    else:
        out_dir = os.path.normpath(os.path.expanduser(dir_raw))
        if not os.path.isabs(out_dir):
            errors.append(f"env.dir {dir_raw!r} must be absolute (or start with ~)")

    launchd = raw.get("launchd", False)
    if not isinstance(launchd, bool):
        errors.append("env.launchd must be true or false")

    if errors:
        return None, errors
    return Spec(env_vars, path, shells, out_dir, launchd), []


# --------------------------------------------------------------------------
# Rendering
# --------------------------------------------------------------------------


def _sh_quote(value: str) -> str:
    return "'" + value.replace("'", "'\\''") + "'"


def _fish_quote(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def _nu_quote(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


# Moves $1 to the front of PATH, dropping every other copy. Pure parameter
# expansion: zsh does not word-split, so IFS tricks would not be portable.
_SH_PREPEND = """\
__tools_env_prepend() {
  __tools_p=":${PATH-}:"
  while :; do
    case "$__tools_p" in
      *":$1:"*) __tools_p="${__tools_p%%":$1:"*}:${__tools_p#*":$1:"}" ;;
      *) break ;;
    esac
  done
  __tools_p="${__tools_p#:}"
  __tools_p="${__tools_p%:}"
  PATH="$1${__tools_p:+:$__tools_p}"
  unset __tools_p
}
"""


def _render_sh(spec: Spec) -> str:
    lines = [f"# {_HEADER}"]
    lines += [f"export {name}={_sh_quote(value)}" for name, value in spec.vars.items()]
    if spec.path:
        lines.append(_SH_PREPEND.rstrip("\n"))
        lines += [f"__tools_env_prepend {_sh_quote(p)}" for p in reversed(spec.path)]
        lines += ["unset -f __tools_env_prepend", "export PATH"]
    return "\n".join(lines) + "\n"


def _render_fish(spec: Spec) -> str:
    lines = [f"# {_HEADER}"]
    lines += [f"set -gx {name} {_fish_quote(value)}" for name, value in spec.vars.items()]
    if spec.path:
        dirs = " ".join(_fish_quote(p) for p in reversed(spec.path))
        lines += [
            f"for __tools_d in {dirs}",
            "    while set -l __tools_i (contains -i -- $__tools_d $PATH)",
            "        set -e PATH[$__tools_i]",
            "    end",
            "    set -gx PATH $__tools_d $PATH",
            "end",
            "set -e __tools_d",
        ]
    return "\n".join(lines) + "\n"


def _render_nu(spec: Spec) -> str:
    lines = [f"# {_HEADER}"]
    if spec.vars:
        lines.append("load-env {")
        lines += [f"    {_nu_quote(n)}: {_nu_quote(v)}" for n, v in spec.vars.items()]
        lines.append("}")
    if spec.path:
        dirs = "[" + ", ".join(_nu_quote(p) for p in spec.path) + "]"
        lines.append(
            f"$env.PATH = ($env.PATH | split row (char esep) | where {{|p| $p not-in {dirs} }}"
            f" | prepend {dirs})"
        )
    return "\n".join(lines) + "\n"


_RENDERERS = {"sh": _render_sh, "fish": _render_fish, "nu": _render_nu}


def render(spec: Spec, shell: str) -> bytes:
    return _RENDERERS[shell](spec).encode()


