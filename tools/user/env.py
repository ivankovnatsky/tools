def install_env(raw, state: Dict, conflicts=None, run: Optional[Callable] = None) -> bool:
    section = state.setdefault("env", {})
    installed: Dict[str, Dict] = dict(section.get("files", {}) or {})
    tracked_env: Dict[str, str] = dict(section.get("launchd", {}) or {})
    run = run or _launchctl
    p = plan(raw, state, conflicts, run)
    if p.errors:
        for err in p.errors:
            log(f"env: {err}", Color.RED)
        return False
    for warning in p.warnings:
        log(f"env: {warning}", Color.YELLOW)
    success = True
    for target, reason in p.blocked:
        log(f"env: skipping {target}: {reason}", Color.YELLOW)
        success = False

    for target, file_hash in p.adopt:
        installed[target] = {"hash": file_hash}
    labels = {"create": "Created", "update": "Updated", "replace": "Replaced"}
    for target, data, action, aside in p.write:
        try:
            os.makedirs(os.path.dirname(target), exist_ok=True)
            if action == "create":
                moved, aside = fsutil.create_or_replace(target, data, FILE_MODE)
            else:
                moved = fsutil.atomic_write(target, data, FILE_MODE, backup=aside is not None)
        except OSError as e:
            log(f"env: failed to write {target}: {e}", Color.RED)
            success = False
            continue
        if moved:
            log(f"Moved aside ({aside}): {target} -> {moved}", Color.YELLOW)
        installed[target] = {"hash": _hash(data)}
        log(f"{labels[action]}: {target}", Color.GREEN)

    for target, reason in p.forget:
        if reason != "already gone":
            log(f"env: releasing {target}: {reason}", Color.YELLOW)
        installed.pop(target, None)
    for target in p.remove:
        try:
            os.remove(target)
        except OSError as e:
            log(f"env: failed to remove {target}: {e}", Color.RED)
            success = False
            continue
        installed.pop(target, None)
        log(f"Removed: {target}", Color.RED)

    for name, value in p.setenv:
        rc, err = run(["setenv", name, value])
        if rc != 0:
            log(f"env: launchctl setenv {name} failed: {err}", Color.RED)
            success = False
            continue
        tracked_env[name] = value
        log(f"launchctl setenv {name}", Color.GREEN)
    if p.spec and p.spec.launchd:
        # Already holding the desired value: adopted, as links adopts a matching symlink.
        for name, value in p.spec.vars.items():
            if name not in tracked_env and (name, value) not in p.setenv:
                tracked_env[name] = value
    for name, reason in p.launchd_forget:
        if reason != "already unset":
            log(f"env: releasing launchd {name}: {reason}", Color.YELLOW)
        tracked_env.pop(name, None)
    for name in p.unsetenv:
        rc, err = run(["unsetenv", name])
        if rc != 0:
            log(f"env: launchctl unsetenv {name} failed: {err}", Color.RED)
            success = False
            continue
        tracked_env.pop(name, None)
        log(f"launchctl unsetenv {name}", Color.RED)

    # Only what every snippet now says; a failed write keeps the old rows in the diff.
    if p.spec and success:
        section["vars"] = dict(p.spec.vars)
        section["path"] = list(p.spec.path)
    elif not p.spec and not installed:
        section.pop("vars", None)
        section.pop("path", None)
    section["files"] = installed
    section["launchd"] = tracked_env
    if not (p.write or p.remove or p.setenv or p.unsetenv):
        debug("env up to date", Color.BLUE)
    return success


# --------------------------------------------------------------------------
# Diff (read-only)
# --------------------------------------------------------------------------


def diff_env(raw, state: Dict, conflicts=None, run: Optional[Callable] = None) -> List[str]:
    p = plan(raw, state, conflicts, run)
    if p.errors:
        return [f"  ! {err}" for err in p.errors]
    rows = [f"  ! {w}" for w in p.warnings]
    if p.write or p.remove or p.setenv or p.unsetenv:
        rows += p.var_rows
    verbs = {"create": "+ write", "update": "~ update", "replace": "~ replace"}
    for target, _data, action, aside in p.write:
        suffix = f" ({fsutil.aside_note(target, aside)})" if aside else ""
        rows.append(f"  {verbs[action]} {target}{suffix}")
    rows += [f"  ! skip {t}: {reason}" for t, reason in p.blocked]
    rows += fsutil.describe_removals([], p.remove, [f for f in p.forget if f[1] != "already gone"])
    rows += [f"  + launchctl setenv {name}={value}" for name, value in p.setenv]
    rows += [f"  - launchctl unsetenv {name}" for name in p.unsetenv]
    rows += [
        f"  ~ forget launchd {name} ({reason})"
        for name, reason in p.launchd_forget
        if reason != "already unset"
    ]
    return rows


def has_work(raw, state: Dict) -> bool:
    section = state.get("env", {}) or {}
    return bool(raw) or bool(section.get("files") or section.get("launchd"))
